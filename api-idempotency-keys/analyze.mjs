#!/usr/bin/env node
// Summarize results/main/runs.csv and results/gap/runs.csv into results/summary.md,
// results/summary.csv, and an SVG chart of double charges by gap between duplicates.
//
//   node analyze.mjs

import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const readCsv = (path) => {
  const [head, ...body] = readFileSync(path, 'utf8').trim().split('\n')
  const names = head.split(',')
  return body.map((line) => {
    const row = Object.fromEntries(line.split(',').map((v, i) => [names[i], v]))
    for (const k of Object.keys(row)) if (row[k] !== '' && !isNaN(Number(row[k]))) row[k] = Number(row[k])
    return row
  })
}
const median = (xs) => {
  const s = xs.filter((x) => x !== '' && x != null).sort((a, b) => a - b)
  if (!s.length) return null
  const m = Math.floor(s.length / 2)
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2
}
const pct = (n, d) => (d ? Math.round((n / d) * 1000) / 10 : null)

const IMPL_LABEL = {
  none: 'No idempotency',
  check_then_insert: 'Check, then insert',
  redis_lock: 'Redis SET NX lock',
  reserve: 'Reservation (ON CONFLICT)',
  reserve_release: 'Reservation, key freed on error',
  reserve_provider_key: 'Reservation + provider key',
}
const SCENARIO_LABEL = {
  concurrent_2: '2 at once',
  concurrent_10: '10 at once',
  client_retry: 'Client timeout + retry',
  slow_provider: 'Provider slower than lock TTL',
  lost_response: 'Lost provider response',
}

const main = readCsv(join(HERE, 'results', 'main', 'runs.csv'))
const impls = Object.keys(IMPL_LABEL).filter((i) => main.some((r) => r.impl === i))
const scenarios = Object.keys(SCENARIO_LABEL).filter((s) => main.some((r) => r.scenario === s))

const summary = []
for (const impl of impls)
  for (const scenario of [...scenarios, 'key_reuse']) {
    const runs = main.filter((r) => r.impl === impl && r.scenario === scenario)
    if (!runs.length) continue
    const orders = runs[0].orders
    summary.push({
      impl, scenario, reps: runs.length, orders,
      double_charged_pct: scenario === 'key_reuse' ? '' : pct(median(runs.map((r) => r.orders_double_charged)), orders),
      double_charged_min: scenario === 'key_reuse' ? '' : Math.min(...runs.map((r) => r.orders_double_charged)),
      double_charged_max: scenario === 'key_reuse' ? '' : Math.max(...runs.map((r) => r.orders_double_charged)),
      extra_charges_per_1000: scenario === 'key_reuse' ? '' : Math.round((median(runs.map((r) => r.duplicate_charges)) / orders) * 1000),
      success_pct: pct(median(runs.map((r) => r.final_success)), orders),
      pending_pct: pct(median(runs.map((r) => r.final_pending)), orders),
      error_pct: pct(median(runs.map((r) => r.final_error)), orders),
      wrong_payment_returned: median(runs.map((r) => r.wrong_payment_returned)),
      reuse_rejected_pct: scenario === 'key_reuse' ? pct(median(runs.map((r) => r.reuse_rejected)), orders) : '',
      reuse_wrong_replay_pct: scenario === 'key_reuse' ? pct(median(runs.map((r) => r.reuse_wrong_replay)), orders) : '',
      reuse_charged_new_pct: scenario === 'key_reuse' ? pct(median(runs.map((r) => r.reuse_charged_new)), orders) : '',
      p50_ms: median(runs.map((r) => r.p50_ms)),
      p95_ms: median(runs.map((r) => r.p95_ms)),
    })
  }

const cols = Object.keys(summary[0])
writeFileSync(join(HERE, 'results', 'summary.csv'), [cols.join(','), ...summary.map((s) => cols.map((c) => s[c] ?? '').join(','))].join('\n') + '\n')

const get = (impl, scenario) => summary.find((s) => s.impl === impl && s.scenario === scenario)
let md = `# Results\n\nGenerated by \`node analyze.mjs\`. Medians of ${Math.max(...summary.map((s) => s.reps))} runs of ${summary[0].orders} payments each; the provider's ledger is the ground truth for charges.\n`

md += `\n## Payments charged more than once\n\n| Implementation | ${scenarios.map((s) => SCENARIO_LABEL[s]).join(' | ')} |\n|---|${scenarios.map(() => '---:').join('|')}|\n`
for (const impl of impls) md += `| ${IMPL_LABEL[impl]} | ${scenarios.map((s) => `${get(impl, s)?.double_charged_pct ?? '–'}%`).join(' | ')} |\n`

md += `\n## Extra charges per 1,000 payments\n\n| Implementation | ${scenarios.map((s) => SCENARIO_LABEL[s]).join(' | ')} |\n|---|${scenarios.map(() => '---:').join('|')}|\n`
for (const impl of impls) md += `| ${IMPL_LABEL[impl]} | ${scenarios.map((s) => (get(impl, s)?.extra_charges_per_1000 ?? '–').toLocaleString('en-US')).join(' | ')} |\n`

md += `\n## What the client ended up with (success / pending / error)\n\n| Implementation | ${scenarios.map((s) => SCENARIO_LABEL[s]).join(' | ')} |\n|---|${scenarios.map(() => '---').join('|')}|\n`
for (const impl of impls)
  md += `| ${IMPL_LABEL[impl]} | ${scenarios.map((s) => {
    const x = get(impl, s)
    return x ? `${x.success_pct}% / ${x.pending_pct}% / ${x.error_pct}%` : '–'
  }).join(' | ')} |\n`

md += `\n## Same key reused for a different payment\n\n| Implementation | Rejected | Replayed the first payment | Charged the new payment |\n|---|---:|---:|---:|\n`
for (const impl of impls) {
  const x = get(impl, 'key_reuse')
  if (x) md += `| ${IMPL_LABEL[impl]} | ${x.reuse_rejected_pct}% | ${x.reuse_wrong_replay_pct}% | ${x.reuse_charged_new_pct}% |\n`
}

const spread = summary.filter((s) => s.double_charged_max !== '' && s.double_charged_max - s.double_charged_min > 0)
md += `\n## Consistency across repeats\n\nCells where the number of double-charged payments differed between repeats: ${spread.length} of ${summary.filter((s) => s.double_charged_max !== '').length}.\n`
for (const s of spread) md += `- ${IMPL_LABEL[s.impl]}, ${SCENARIO_LABEL[s.scenario]}: ${s.double_charged_min} to ${s.double_charged_max} of ${s.orders}\n`
const wrong = summary.filter((s) => s.wrong_payment_returned)
md += wrong.length ? `\n**Wrong payment returned** (success response naming a charge that does not belong to that key): ${wrong.map((s) => `${s.impl}/${s.scenario}=${s.wrong_payment_returned}`).join(', ')}\n` : '\nNo success response named a charge that did not belong to its key.\n'

// Gap sweep: share of payments charged twice when the duplicate arrives N ms after the first request.
const gapPath = join(HERE, 'results', 'gap', 'runs.csv')
if (existsSync(gapPath)) {
  const gap = readCsv(gapPath)
  const points = [...new Set(gap.map((r) => Number(r.scenario.replace('gap_', ''))))].sort((a, b) => a - b).map((ms) => {
    const runs = gap.filter((r) => r.scenario === `gap_${ms}`)
    return { ms, pct: pct(median(runs.map((r) => r.orders_double_charged)), runs[0].orders), min: Math.min(...runs.map((r) => r.orders_double_charged)), max: Math.max(...runs.map((r) => r.orders_double_charged)), orders: runs[0].orders }
  })
  md += `\n## Check, then insert: duplicate arriving N ms after the first request\n\nProvider latency 100 ± 50 ms.\n\n| Gap | Payments charged twice | Range across repeats |\n|---:|---:|---:|\n`
  for (const p of points) md += `| ${p.ms} ms | ${p.pct}% | ${p.min}–${p.max} of ${p.orders} |\n`

  const W = 720, H = 400, L = 70, R = 20, T = 50, B = 70
  const maxX = Math.max(...points.map((p) => p.ms))
  const xPos = (x) => L + (x / maxX) * (W - L - R)
  const yPos = (y) => T + (1 - y / 100) * (H - T - B)
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" font-family="system-ui, -apple-system, Segoe UI, sans-serif" font-size="13">\n<rect width="${W}" height="${H}" fill="#ffffff"/>\n`
  svg += `<text x="${L}" y="28" font-size="16" font-weight="600" fill="#111">Check, then insert: payments charged twice by gap between duplicates</text>\n`
  for (let y = 0; y <= 100; y += 25) svg += `<line x1="${L}" x2="${W - R}" y1="${yPos(y)}" y2="${yPos(y)}" stroke="#e5e7eb"/><text x="${L - 8}" y="${yPos(y) + 4}" text-anchor="end" fill="#4b5563">${y}%</text>\n`
  for (const p of points) svg += `<text x="${xPos(p.ms)}" y="${H - B + 20}" text-anchor="middle" fill="#4b5563">${p.ms}</text>\n`
  // Shade the provider's latency range (50 to 150 ms).
  svg += `<rect x="${xPos(50)}" y="${T}" width="${xPos(150) - xPos(50)}" height="${H - T - B}" fill="#2e86ab" opacity="0.08"/>`
  svg += `<text x="${xPos(150) + 8}" y="${T + 16}" text-anchor="start" fill="#2e86ab">← shaded: provider latency 50–150 ms</text>\n`
  svg += `<path d="${points.map((p, i) => `${i ? 'L' : 'M'}${xPos(p.ms).toFixed(1)},${yPos(p.pct).toFixed(1)}`).join(' ')}" fill="none" stroke="#d1495b" stroke-width="2.5"/>\n`
  for (const p of points) svg += `<circle cx="${xPos(p.ms).toFixed(1)}" cy="${yPos(p.pct).toFixed(1)}" r="4" fill="#d1495b"/>`
  svg += `\n<text x="${(L + W - R) / 2}" y="${H - B + 42}" text-anchor="middle" fill="#111">Milliseconds between the first request and its duplicate</text>\n`
  svg += `<text transform="translate(18 ${(T + H - B) / 2}) rotate(-90)" text-anchor="middle" fill="#111">Payments charged twice</text>\n</svg>\n`
  mkdirSync(join(HERE, 'results', 'charts'), { recursive: true })
  writeFileSync(join(HERE, 'results', 'charts', 'gap.svg'), svg)
}

writeFileSync(join(HERE, 'results', 'summary.md'), md)
console.log(md)
